// This file encodes and decodes herdr-core's frames: a 9-byte header of
// channel, kind and payload length, then the payload.

package hc

import (
	"encoding/binary"
	"errors"
	"fmt"
	"io"
)

type (
	// frameKind is the one-byte kind in a frame header. The values are
	// herdr-core's wire constants, so their order must not change.
	frameKind uint8

	// frame is one decoded frame: the channel it belongs to, its kind and
	// payload.
	frame struct {
		channel uint32
		kind    frameKind
		payload []byte
	}
)

const (
	// kindData carries one JSON-RPC message on channel 0 and stream bytes on
	// every other channel.
	kindData frameKind = iota
	// kindCredit carries a little-endian u32: how many stream bytes the
	// receiver consumed, so the sender may send that many more.
	kindCredit
	// kindClose ends a channel. The core sends a JSON reason; a client sends
	// an empty payload.
	kindClose
	// kindResize carries little-endian u16 columns then u16 rows.
	kindResize
	// kindFocus carries one byte: 1 when the viewer gained focus, 0 when it
	// lost it.
	kindFocus
	// kindFacts carries a viewer's JSON display facts. This client sends them
	// in the attach request instead, so it never sends this kind.
	kindFacts
	// kindAutomaticInput carries bytes a terminal emulator generated by
	// itself, which the core does not count as a person typing.
	kindAutomaticInput
)

const (
	// headerSize is the fixed frame header: channel u32 LE, kind u8, length
	// u32 LE.
	headerSize = 9
	// MaxPayload is the largest frame payload either side may send.
	MaxPayload = 16 << 20
	// window is the stream credit, in bytes, that a channel starts with before
	// its receiver acknowledges anything.
	window = 256 << 10
	// inputChunk bounds one input frame so a large paste does not hold the
	// connection's write lock for its whole length.
	inputChunk = 64 << 10
)

// appendFrame appends the encoded frame to dst and returns the extended slice.
// The caller guarantees len(payload) <= MaxPayload.
func appendFrame(dst []byte, channel uint32, kind frameKind, payload []byte) []byte {
	dst = binary.LittleEndian.AppendUint32(dst, channel)
	dst = append(dst, byte(kind))
	dst = binary.LittleEndian.AppendUint32(dst, uint32(len(payload)))
	return append(dst, payload...)
}

// readFrame reads one frame. It returns io.EOF when the stream ends between
// frames, io.ErrUnexpectedEOF when it ends inside one, and ErrProtocol when the
// header announces more than MaxPayload bytes; the length is checked before
// any payload byte is read.
func readFrame(r io.Reader) (frame, error) {
	var header [headerSize]byte
	if _, err := io.ReadFull(r, header[:]); err != nil {
		return frame{}, err
	}
	size := binary.LittleEndian.Uint32(header[5:])
	if size > MaxPayload {
		return frame{}, fmt.Errorf("%w: frame of %d bytes exceeds %d", ErrProtocol, size, MaxPayload)
	}
	payload := make([]byte, size)
	if _, err := io.ReadFull(r, payload); err != nil {
		if errors.Is(err, io.EOF) {
			err = io.ErrUnexpectedEOF
		}
		return frame{}, err
	}
	return frame{
		channel: binary.LittleEndian.Uint32(header[:4]),
		kind:    frameKind(header[4]),
		payload: payload,
	}, nil
}
