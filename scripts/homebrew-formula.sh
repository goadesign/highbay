#!/bin/sh
# Emit Formula/highbay.rb using the SHA-256 values published with one release.
# Usage: scripts/homebrew-formula.sh VERSION CHECKSUMS_FILE
set -eu

if [ "$#" -ne 2 ]; then
  printf 'usage: %s VERSION CHECKSUMS_FILE\n' "$0" >&2
  exit 2
fi
version=$1
checksums=$2
case $version in
  ''|*[!0-9.]*) printf 'Expected a stable release version\n' >&2; exit 1 ;;
esac
if ! printf '%s\n' "$version" | grep -Eq '^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$'; then
  printf 'Invalid release version: %s\n' "$version" >&2
  exit 1
fi

digest() {
  archive="highbay_${version}_$1_$2.tar.gz"
  if ! awk -v archive="$archive" '
    NF == 2 && ($2 == archive || $2 == "*" archive) { digest = $1; count++ }
    END {
      if (count != 1 || length(digest) != 64 || digest ~ /[^[:xdigit:]]/) exit 1
      print tolower(digest)
    }
  ' "$checksums"; then
    printf 'Expected one SHA-256 checksum for %s\n' "$archive" >&2
    return 1
  fi
}

darwin_arm64=$(digest darwin arm64)
darwin_amd64=$(digest darwin amd64)
linux_arm64=$(digest linux arm64)
linux_amd64=$(digest linux amd64)
base="https://github.com/goadesign/highbay/releases/download/v${version}"

cat <<FORMULA
# Generated by scripts/homebrew-formula.sh in goadesign/highbay.
class Highbay < Formula
  desc "Build Go services and agents with checkpoints you approve in your browser"
  homepage "https://github.com/goadesign/highbay"
  version "${version}"
  license "MIT"

  depends_on "git"
  depends_on "go"
  depends_on "goadesign/tap/chorus"

  on_macos do
    on_arm do
      url "${base}/highbay_${version}_darwin_arm64.tar.gz"
      sha256 "${darwin_arm64}"
    end

    on_intel do
      url "${base}/highbay_${version}_darwin_amd64.tar.gz"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/highbay_${version}_linux_arm64.tar.gz"
      sha256 "${linux_arm64}"
    end

    on_intel do
      url "${base}/highbay_${version}_linux_amd64.tar.gz"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "highbay"
  end

  def caveats
    "Run highbay up once, then run highbay in your project to open the browser workspace."
  end

  test do
    assert_equal "v#{version}", shell_output("#{bin}/highbay version").strip
  end
end
FORMULA
